//! Feed expiry after the production retention verb prunes history.

#![cfg(feature = "ops")]

use serde_json::json;
use tokio_postgres::{Client, NoTls};
use wamn_control::prune_record_history::prune;
use wamn_schema_generator::{GenerationInput, StatementTransactionality, generate};

async fn fixture() -> (wamn_test_postgres::Database, Client, String) {
    let database = wamn_test_postgres::database();
    let (client, connection) = tokio_postgres::connect(database.url(), NoTls)
        .await
        .expect("connect to the fixture database");
    tokio::spawn(async move {
        let _ = connection.await;
    });
    for role in ["wamn_app", "wamn_scenario_author"] {
        client
            .batch_execute(&format!(
                "DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{role}') \
                 THEN CREATE ROLE {role} NOLOGIN; END IF; END $$"
            ))
            .await
            .expect("create the fixture roles");
    }
    client
        .batch_execute(wamn_catalog::CATALOG_SCHEMA_SQL)
        .await
        .expect("install history functions and platform principals");
    client
        .batch_execute(
            "CREATE SCHEMA inventory; \
             SET search_path TO inventory, public; \
             CREATE TABLE inventory.widget (id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT widget_id_pkey PRIMARY KEY, row_version bigint NOT NULL, \
                                           created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP);",
        )
        .await
        .expect("create the logged model");
    let catalog = wamn_schema_introspection::postgres::read_catalog(&client, &["inventory"])
        .await
        .expect("read the model catalog");
    let manifest = serde_json::to_vec(&json!({
        "package": {"id": "watermark_fixture", "version": "1.0.0"},
        "required_platform_policy_contract": {"id": "widget_data_access", "state": "unsatisfied"},
        "connections": ["postgres"],
        "components": {"inventory": {"connections": ["postgres"]}},
        "models": {"widget": {
            "schema": "inventory", "table": "widget", "owner": "watermark_fixture",
            "server_owned_fields": ["id", "row_version", "created_at"],
            "audit_log": {"columns": ["created_at"], "retention": "P30D"},
            "operations": {"query": {
                "permission": "widget.query", "result": "page", "revision_field": "row_version",
                "sort": {"fields": ["created_at"], "directions": ["ascending"]},
                "pagination": {"default_sort": {"field": "created_at", "direction": "ascending"},
                               "tie_breaker": {"field": "id"}},
                "limit": {"default": 100, "minimum": 1, "maximum": 100}
            }}
        }}
    }))
    .unwrap();
    let generated = generate(&GenerationInput::new(
        &catalog,
        &manifest,
        &[],
        &StatementTransactionality::default(),
    ))
    .expect("generate the changes call");
    let changes = std::str::from_utf8(
        generated
            .file("generated/sql/widget/changes.sql")
            .expect("the model has a feed")
            .bytes(),
    )
    .unwrap()
    .to_owned();
    client
        .batch_execute(
            "SELECT wamn_history.create_history_table('inventory', 'widget', false); \
             CREATE TRIGGER wamn_record_history_log AFTER INSERT OR UPDATE OR DELETE \
               ON inventory.widget FOR EACH ROW EXECUTE FUNCTION wamn_history.log_row_change('P30D'); \
             GRANT USAGE ON SCHEMA inventory TO wamn_app; \
             GRANT SELECT ON inventory.widget, inventory.widget_history TO wamn_app; \
             SELECT set_config('app.user_id', '00000000-0000-4000-8000-000000000001', false), \
                    set_config('app.operation', 'admin:seed-history-fixture', false);",
        )
        .await
        .expect("install history and seed authority");
    (database, client, changes)
}

async fn cursor(client: &Client) -> i64 {
    client
        .query_one(
            "SELECT pg_snapshot_xmin(pg_current_snapshot())::text::bigint",
            &[],
        )
        .await
        .expect("read a feed cursor")
        .get(0)
}

async fn changes_expired(client: &Client, changes: &str, cursor: i64) -> bool {
    client.batch_execute("SET ROLE wamn_app").await.unwrap();
    let row = client
        .query_one(changes, &[&cursor, &None::<i64>, &101_i64])
        .await
        .expect("call generated changes as the guest");
    client.batch_execute("RESET ROLE").await.unwrap();
    // Generated data::changes maps this result to Error::cursor_expired().
    row.get("expired")
}

async fn prune_as_retention(client: &mut Client) -> u64 {
    client
        .batch_execute(
            &wamn_control_provision::audit_retention::reconcile_audit_retention_grants_sql(),
        )
        .await
        .expect("grant the retention surface");
    client
        .batch_execute("SET ROLE wamn_audit_retention")
        .await
        .unwrap();
    let pruned = prune(client).await.expect("prune as the retention role");
    client.batch_execute("RESET ROLE").await.unwrap();
    assert_eq!(pruned.len(), 1);
    pruned[0].removed
}

async fn age_history(client: &Client) {
    client
        .batch_execute(
            "UPDATE inventory.widget_history SET changed_at = now() - interval '40 days'",
        )
        .await
        .unwrap();
}

#[tokio::test]
async fn pruning_every_entry_expires_the_cursor() {
    let _lock = wamn_test_postgres::lock();
    let (_database, mut client, changes) = fixture().await;
    // Start from the old storage and grants, then apply the upgrade.
    client
        .batch_execute(
            "DROP TABLE wamn_history.pruning_watermarks; \
                        GRANT USAGE ON SCHEMA inventory TO wamn_audit_retention; \
                        GRANT DELETE, SELECT (row_key, position, changed_at) \
                          ON inventory.widget_history TO wamn_audit_retention;",
        )
        .await
        .unwrap();
    client
        .batch_execute(include_str!(
            "../../../../deploy/sql/migrations/project/0041_history_pruning_watermarks.sql"
        ))
        .await
        .expect("upgrade the history storage and retention grants");
    let upgraded: bool = client
        .query_one(
            "SELECT has_table_privilege('wamn_audit_retention', \
                       'wamn_history.pruning_watermarks', 'INSERT') \
                     AND has_table_privilege('wamn_audit_retention', \
                       'wamn_history.pruning_watermarks', 'UPDATE') \
                     AND has_table_privilege('wamn_audit_retention', \
                       'wamn_history.pruning_watermarks', 'SELECT') \
                     AND has_column_privilege('wamn_audit_retention', \
                       'inventory.widget_history', 'transaction_id', 'SELECT')",
            &[],
        )
        .await
        .unwrap()
        .get(0);
    assert!(upgraded);
    let before = cursor(&client).await;
    assert!(!changes_expired(&client, &changes, before).await);
    client
        .batch_execute("INSERT INTO inventory.widget (id, row_version) VALUES (1, 1)")
        .await
        .unwrap();
    client
        .batch_execute("DELETE FROM inventory.widget WHERE id = 1")
        .await
        .unwrap();
    let highest: i64 = client
        .query_one(
            "SELECT max(transaction_id) FROM inventory.widget_history",
            &[],
        )
        .await
        .unwrap()
        .get(0);
    age_history(&client).await;
    assert_eq!(prune_as_retention(&mut client).await, 2);
    let remaining: i64 = client
        .query_one("SELECT count(*) FROM inventory.widget_history", &[])
        .await
        .unwrap()
        .get(0);
    assert_eq!(remaining, 0);
    assert!(changes_expired(&client, &changes, before).await);
    assert!(changes_expired(&client, &changes, highest).await);
    assert!(!changes_expired(&client, &changes, highest + 1).await);
    assert_eq!(prune_as_retention(&mut client).await, 0);
    assert!(changes_expired(&client, &changes, highest).await);
}

#[tokio::test]
async fn a_cursor_newer_than_the_watermark_does_not_expire() {
    let _lock = wamn_test_postgres::lock();
    let (_database, mut client, changes) = fixture().await;
    client
        .batch_execute("INSERT INTO inventory.widget (id, row_version) VALUES (1, 1)")
        .await
        .unwrap();
    let idle = cursor(&client).await;
    age_history(&client).await;
    client
        .batch_execute("INSERT INTO inventory.widget (id, row_version) VALUES (2, 1)")
        .await
        .unwrap();
    assert_eq!(prune_as_retention(&mut client).await, 1);
    let first_retained: i64 = client
        .query_one(
            "SELECT min(transaction_id) FROM inventory.widget_history",
            &[],
        )
        .await
        .unwrap()
        .get(0);
    assert!(idle < first_retained);
    assert!(!changes_expired(&client, &changes, idle).await);
    age_history(&client).await;
    assert_eq!(prune_as_retention(&mut client).await, 1);
    assert!(changes_expired(&client, &changes, idle).await);
}
