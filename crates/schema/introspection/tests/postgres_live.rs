//! Selected columns supply the generated action's transport types.

use sqlx::{AssertSqlSafe, Row as _, SqlSafeStr as _};
use wamn_scalar::SqlValueType;
use wamn_schema_introspection::postgres::{
    PostgresIntrospectionErrorType, read_catalog, read_catalog_excluding_relations,
};

#[tokio::test]
async fn selected_columns_fit_the_action() {
    let database = wamn_test_postgres::database();
    let pool = wamn_postgres::pool(database.url(), 4).await.unwrap();
    sqlx::raw_sql(AssertSqlSafe("CREATE SCHEMA application;
        CREATE TABLE application.item (id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT item_id_pkey PRIMARY KEY, label text, quantity int2, ratio float4, code char(2));
        CREATE FUNCTION application.authored() RETURNS bigint LANGUAGE SQL AS 'SELECT 1';
        CREATE DOMAIN application.unused AS text;
        CREATE TABLE application.unused_data (value date);
        CREATE SEQUENCE application.unused_sequence START 2;
        CREATE VIEW application.item_view AS SELECT id, label FROM application.item;
        INSERT INTO application.item VALUES (7, NULL, 3, 0.5, 'ab')".to_owned()).into_sql_str()).execute(&pool).await.unwrap();
    let catalog = read_catalog_excluding_relations(
        &pool,
        &["application"],
        &[("application", "unused_data")],
    )
    .await
    .unwrap();
    let table = &catalog.tables()[0];
    let columns = table
        .columns()
        .iter()
        .map(|column| (column.name(), column.column_type()))
        .collect::<std::collections::BTreeMap<_, _>>();
    let row = sqlx::query(
        AssertSqlSafe(
            "SELECT id, label, quantity::int4, ratio::float8, code::text FROM application.item"
                .to_owned(),
        )
        .into_sql_str(),
    )
    .fetch_one(&pool)
    .await
    .unwrap();
    assert_eq!(row.get::<i64, _>(0), 7);
    assert!(row.get::<Option<String>, _>(1).is_none());
    assert_eq!(row.get::<i32, _>(2), 3);
    assert!(row.get::<f64, _>(3).is_finite());
    assert_eq!(columns["id"], SqlValueType::Int64);
    assert_eq!(columns["label"], SqlValueType::Text);
    assert_eq!(columns["quantity"], SqlValueType::Int32);
    assert_eq!(columns["ratio"], SqlValueType::Float64);
    assert_eq!(columns["code"], SqlValueType::Text);
    let view = &catalog.views()[0];
    assert_eq!(view.columns()[0].column_type(), SqlValueType::Int64);
    assert_eq!(view.columns()[1].column_type(), SqlValueType::Text);
    assert!(
        view.columns()
            .iter()
            .all(|column| column.origin().is_some())
    );
    pool.close().await;
}

#[tokio::test]
async fn selected_column_and_constraint_refusals_remain() {
    for (definition, expected) in [
        (
            "CREATE TABLE application.dock (dock_id uuid NOT NULL, CONSTRAINT incorrect EXCLUDE USING gist (dock_id WITH =))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE application.dock (dock_id uuid NOT NULL, CONSTRAINT dock_dock_id_excl EXCLUDE USING btree (dock_id WITH =))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE application.dock (dock_id uuid NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL, CONSTRAINT dock_excl EXCLUDE USING gist (dock_id WITH =, tstzrange(starts_at, ends_at) WITH &&) WHERE (ends_at > starts_at))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE application.dock (dock_id uuid NOT NULL, CONSTRAINT dock_dock_id_excl EXCLUDE USING gist (dock_id WITH =) DEFERRABLE INITIALLY DEFERRED)",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE application.item (id date)",
            PostgresIntrospectionErrorType::UnsupportedColumnType,
        ),
        (
            "CREATE TABLE application.item (name text DEFAULT lower('CLOSED'))",
            PostgresIntrospectionErrorType::UnsupportedColumnDefault,
        ),
        (
            "CREATE TABLE application.item (name text, computed text GENERATED ALWAYS AS (lower(name)) VIRTUAL)",
            PostgresIntrospectionErrorType::UnsupportedGeneratedColumn,
        ),
        (
            "CREATE TABLE application.item (name text); CREATE INDEX item_name_expression_idx ON application.item(lower(name))",
            PostgresIntrospectionErrorType::UnsupportedIndex,
        ),
        (
            "CREATE TABLE application.item (name text); CREATE INDEX refused_name ON application.item(name)",
            PostgresIntrospectionErrorType::UnsupportedIndex,
        ),
        (
            "CREATE TABLE application.item (name text); CREATE INDEX item_name_name_idx ON application.item(name,name)",
            PostgresIntrospectionErrorType::UnsupportedIndex,
        ),
        (
            "CREATE TABLE application.item (name text CONSTRAINT refused_name CHECK (name <> ''))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
    ] {
        let database = wamn_test_postgres::database();
        let pool = wamn_postgres::pool(database.url(), 4).await.unwrap();
        sqlx::raw_sql(
            AssertSqlSafe(format!(
                "CREATE EXTENSION btree_gist; CREATE SCHEMA application; {definition}"
            ))
            .into_sql_str(),
        )
        .execute(&pool)
        .await
        .unwrap();
        assert_eq!(
            read_catalog(&pool, &["application"])
                .await
                .unwrap_err()
                .error_type(),
            expected
        );
        pool.close().await;
    }
}

#[tokio::test]
async fn views_preserve_origins_expansion_dependencies_and_set_returning_functions() {
    let database = wamn_test_postgres::database();
    let pool = wamn_postgres::pool(database.url(), 4).await.unwrap();
    sqlx::raw_sql(AssertSqlSafe("CREATE SCHEMA application;
        CREATE TABLE application.item (id bigint, label text);
        CREATE TABLE application.other (id bigint);
        CREATE VIEW application.inner_view (direct, computed, expanded_id, expanded_label) AS
            SELECT item.id, upper(label), (item).* FROM application.item JOIN application.other USING (id);
        CREATE VIEW application.outer_view AS SELECT * FROM application.inner_view;
        CREATE VIEW application.expanded AS SELECT id, unnest(ARRAY[id]) AS each FROM application.item".to_owned()).into_sql_str()).execute(&pool).await.unwrap();
    let catalog = read_catalog(&pool, &["application"]).await.unwrap();
    let view = |name| {
        catalog
            .views()
            .iter()
            .find(|view| view.name() == name)
            .unwrap()
    };
    let inner = view("inner_view");
    let item = catalog
        .tables()
        .iter()
        .find(|table| table.name() == "item")
        .unwrap();
    for (view_column, source_column) in [(0, 0), (2, 0), (3, 1)] {
        assert_eq!(
            inner.columns()[view_column].origin(),
            Some(&wamn_schema_introspection::ir::ViewColumnOrigin {
                schema: item.schema().into(),
                table: item.name().into(),
                column: item.columns()[source_column].name().into(),
            })
        );
    }
    assert!(inner.columns()[1].origin().is_none());
    assert_eq!(view("outer_view").base_tables(), inner.base_tables());
    assert_eq!(
        inner
            .base_tables()
            .iter()
            .map(|table| table.name())
            .collect::<std::collections::BTreeSet<_>>(),
        catalog.tables().iter().map(|table| table.name()).collect()
    );
    assert!(view("expanded").has_set_returning_functions());
    assert!(!inner.has_set_returning_functions());
    assert!(view("expanded").columns()[0].origin().is_some());
    assert!(view("expanded").columns()[1].origin().is_none());
    pool.close().await;
}

#[tokio::test]
async fn selected_relations_retain_outgoing_and_incoming_foreign_keys() {
    use wamn_schema_introspection::ir::ConstraintType;
    let database = wamn_test_postgres::database();
    let pool = wamn_postgres::pool(database.url(), 4).await.unwrap();
    sqlx::raw_sql(AssertSqlSafe("CREATE SCHEMA application;
        CREATE TABLE application.parent (id bigint PRIMARY KEY, unrelated date);
        CREATE TABLE application.selected (id bigint CONSTRAINT selected_id_pkey PRIMARY KEY, parent_id bigint REFERENCES application.parent(id));
        CREATE TABLE application.child (id bigint, selected_id bigint REFERENCES application.selected(id), unrelated date)".to_owned()).into_sql_str()).execute(&pool).await.unwrap();
    let catalog = read_catalog_excluding_relations(
        &pool,
        &["application"],
        &[("application", "parent"), ("application", "child")],
    )
    .await
    .unwrap();
    assert!(
        catalog.tables()[0]
            .constraints()
            .iter()
            .any(|constraint| matches!(
                constraint.constraint_type(),
                ConstraintType::ForeignKey { .. }
            ))
    );
    assert!(!catalog.referencing_constraints().is_empty());
    assert!(
        catalog
            .referencing_constraints()
            .iter()
            .all(|constraint| matches!(
                constraint.constraint_type(),
                ConstraintType::ForeignKey { referenced_table, .. } if referenced_table.as_ref() == catalog.tables()[0].name()
            ))
    );
    pool.close().await;
}
