use std::collections::BTreeMap;

use serde_json::{Value, json};
use sqlx::Row as _;
use wamn_package::manifest::CursorDirection;

use wamn_scalar::SqlValueType;
use wamn_schema::ir::{CatalogIr, Column, Constraint, Table};

fn generated_sql(catalog: &CatalogIr, operations: &Value, statement: &str) -> String {
    let table = &catalog.tables()[0];
    let relation = table.name();
    let path = format!("generated/sql/{relation}/{statement}.sql");
    let manifest = json!({
        "package": {"id": "fixture", "version": "1.0.0"},
        "required_platform_policy_contract": {"id": "fixture", "state": "satisfied"},
        "models": {(relation): {
            "schema": table.schema(), "table": relation, "owner": "fixture",
            "audit_log": {"columns": if table.columns().iter().any(|column| column.name() == "created_at") { vec!["created_at"] } else { vec![] }, "retention": "none"},
            "operations": operations
        }},
        "connections": {}, "components": {"fixture": {}}
    });
    let compiled =
        wamn_codegen::derive_manifest(catalog, &serde_json::to_vec(&manifest).unwrap(), &[], &[])
            .unwrap();
    let package = wamn_codegen::generate(&wamn_codegen::GenerationInput::new(
        catalog,
        &compiled,
        &[],
        &wamn_codegen::StatementTransactionality::from_paths(BTreeMap::new()),
    ))
    .unwrap();
    String::from_utf8(package.file(&path).unwrap().bytes().to_vec()).unwrap()
}

#[tokio::test]
#[ignore = "requires: docker"]
async fn create_returns_database_generated_integer_ids() {
    use wamn_schema::ir::{ColumnDefault, ColumnGeneration, IdentityMode};
    let server = wamn_test_infrastructure::containers::start_postgres()
        .await
        .unwrap();
    let database = server.create_database("tests").await.unwrap();

    let mut client = wamn_postgres::connect(database.as_str()).await.unwrap();

    for (ty, sql_type, expected) in [
        (SqlValueType::Int32, "int4", "2147483647"),
        (SqlValueType::Int64, "int8", "9007199254740993"),
    ] {
        for (generation, mode) in [
            (format!("DEFAULT {expected}"), None),
            (
                format!("GENERATED ALWAYS AS IDENTITY (START WITH {expected})"),
                Some(IdentityMode::Always),
            ),
            (
                format!("GENERATED BY DEFAULT AS IDENTITY (START WITH {expected})"),
                Some(IdentityMode::ByDefault),
            ),
        ] {
            for writable in [false, true] {
                sqlx::raw_sql(sqlx::AssertSqlSafe(format!(
                    "CREATE TABLE key_row (id {sql_type} {generation} PRIMARY KEY, label text DEFAULT 'default');"
                ))).execute(&mut client).await.map(drop).unwrap();
                let table = Table::new(
                    "public",
                    "key_row",
                    vec![
                        Column::new(
                            "id",
                            ty,
                            false,
                            mode.is_none().then(|| match ty {
                                SqlValueType::Int32 => ColumnDefault::int32(2_147_483_647),
                                _ => ColumnDefault::int64(9_007_199_254_740_993),
                            }),
                            mode.map(|mode| ColumnGeneration::Identity { mode }),
                        ),
                        Column::new("label", SqlValueType::Text, true, None, None),
                    ],
                    vec![Constraint::primary_key("key_row_pkey", ["id"]).unwrap()],
                    Vec::new(),
                );
                let sql = if writable {
                    generated_sql(
                        &CatalogIr::new(vec![table]),
                        &json!({
                            "create": {"permission": "key_row.create", "result": "one", "writable_fields": ["label"]}
                        }),
                        "create",
                    )
                } else {
                    include_str!("../../codegen/tests/support/insert_default.sql").to_owned()
                };
                sqlx::raw_sql(sqlx::AssertSqlSafe(format!("PREPARE create_row AS {sql}")))
                    .execute(&mut client)
                    .await
                    .map(drop)
                    .unwrap();
                let rows = sqlx::raw_sql(sqlx::AssertSqlSafe(
                    if writable {
                        "EXECUTE create_row('supplied')"
                    } else {
                        "EXECUTE create_row"
                    }
                    .to_owned(),
                ))
                .fetch_all(&mut client)
                .await
                .unwrap();
                let row = rows.first().unwrap();
                let actual = if ty == SqlValueType::Int32 {
                    i64::from(row.get::<i32, _>("id"))
                } else {
                    row.get::<i64, _>("id")
                };
                assert_eq!(actual, expected.parse::<i64>().unwrap());
                sqlx::raw_sql("DEALLOCATE create_row; DROP TABLE key_row;")
                    .execute(&mut client)
                    .await
                    .map(drop)
                    .unwrap();
            }
        }
    }
    drop(client);
}

#[tokio::test]
#[ignore = "requires: docker"]
async fn query_seeks_and_pages_tied_values_in_both_directions() {
    let server = wamn_test_infrastructure::containers::start_postgres()
        .await
        .unwrap();
    let database = server.create_database("tests").await.unwrap();
    let mut client = wamn_postgres::connect(database.as_str())
        .await
        .expect("connect to the query test database");

    sqlx::raw_sql(sqlx::AssertSqlSafe(
        ("CREATE TABLE page_row (id uuid PRIMARY KEY, rank bigint NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
             CREATE INDEX page_row_rank_id ON page_row (rank, id);
             INSERT INTO page_row (id, rank) SELECT lpad(n::text, 32, '0')::uuid, n / 100
             FROM generate_series(1, 4000) AS n;
             ANALYZE page_row;")
            .to_string(),
    ))
    .execute(&mut client)
    .await
    .map(drop)
    .expect("seed ordered rows with tied sort values");
    let table = Table::new(
        "public",
        "page_row",
        vec![
            Column::new("id", SqlValueType::Uuid, false, None, None),
            Column::new("rank", SqlValueType::Int64, false, None, None),
            Column::new("created_at", SqlValueType::Timestamptz, false, None, None),
        ],
        vec![Constraint::primary_key("page_row_pkey", ["id"]).unwrap()],
        Vec::new(),
    );
    let catalog = CatalogIr::new(vec![table]);
    let operations = json!({"query": {
        "permission": "page_row.query", "result": "page",
        "sort": {"fields": ["created_at", "rank"], "directions": ["ascending", "descending"]},
        "display_field": "rank",
        "pagination": {
            "default_sort": {"field": "created_at", "direction": "ascending"},
            "tie_breaker": {"field": "id"}
        },
        "limit": {"default": 100, "minimum": 1, "maximum": 100},
        "feed": false
    }});
    for direction in [CursorDirection::Ascending, CursorDirection::Descending] {
        let ascending = matches!(direction, CursorDirection::Ascending);
        let suffix = if ascending { "ascending" } else { "descending" };
        let sql = generated_sql(&catalog, &operations, &format!("query_rank_{suffix}"));
        sqlx::raw_sql(sqlx::AssertSqlSafe(format!("PREPARE page AS {sql}")))
            .execute(&mut client)
            .await
            .map(drop)
            .expect("prepare the generated query");
        let mut cursor = "NULL, NULL".to_owned();
        for offset in (0_u32..126).step_by(21) {
            let rows = sqlx::raw_sql(sqlx::AssertSqlSafe(format!("EXECUTE page({cursor}, 21)")))
                .fetch_all(&mut client)
                .await
                .expect("read a generated page");
            let ids = rows
                .iter()
                .map(|row| {
                    row.get::<uuid::Uuid, _>("id")
                        .simple()
                        .to_string()
                        .parse::<u32>()
                        .unwrap()
                })
                .collect::<Vec<_>>();
            let expected = if ascending {
                (offset + 1..=offset + 21).collect::<Vec<_>>()
            } else {
                (4000 - offset - 20..=4000 - offset).rev().collect()
            };
            assert_eq!(
                ids, expected,
                "pages must neither skip nor repeat tied rows"
            );
            let last = rows.last().expect("a full page");
            cursor = format!(
                "{}, '{}'",
                last.get::<i64, _>("rank"),
                last.get::<uuid::Uuid, _>("id")
            );
        }
        let plan: serde_json::Value = sqlx::query("EXPLAIN (ANALYZE, FORMAT JSON) EXECUTE page(20, '00000000-0000-0000-0000-000000002000', 21)").fetch_one(&mut client)
            .await
            .expect("measure a page that starts inside the index")
            .get(0);
        assert!(scanned_rows(&plan[0]["Plan"]) <= 21.0, "{plan}");
        sqlx::raw_sql("DEALLOCATE page")
            .execute(&mut client)
            .await
            .map(drop)
            .unwrap();
    }
    drop(client);
}

fn scanned_rows(plan: &serde_json::Value) -> f64 {
    if plan["Relation Name"] == "page_row" {
        return plan["Actual Rows"].as_f64().unwrap()
            + plan["Rows Removed by Filter"].as_f64().unwrap_or(0.0);
    }
    plan["Plans"]
        .as_array()
        .map_or(0.0, |plans| plans.iter().map(scanned_rows).sum())
}
