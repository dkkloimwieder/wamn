//! Selected columns supply the generated action's transport types.

use sqlx::{AssertSqlSafe, Row as _, SqlSafeStr as _};
use wamn_codegen::catalog::{
    PostgresIntrospectionErrorType, read_catalog, read_catalog_excluding_relations,
};
use wamn_scalar::SqlValueType;

#[tokio::test]
#[ignore = "requires: docker"]
async fn selected_columns_fit_the_action() {
    let server = wamn_test_infrastructure::containers::start_postgres()
        .await
        .unwrap();
    let database = server.create_database("tests").await.unwrap();
    let pool = wamn_postgres::pool(database.as_str(), 4).await.unwrap();
    sqlx::raw_sql(AssertSqlSafe("CREATE SCHEMA app;
        CREATE TABLE app.item (id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT item_id_pkey PRIMARY KEY, label text, quantity int2, ratio float4, code char(2));
        CREATE FUNCTION app.authored() RETURNS bigint LANGUAGE SQL AS 'SELECT 1';
        CREATE DOMAIN app.unused AS text;
        CREATE TABLE app.unused_data (value date);
        CREATE SEQUENCE app.unused_sequence START 2;
        CREATE VIEW app.item_view AS SELECT id, label FROM app.item;
        INSERT INTO app.item VALUES (7, NULL, 3, 0.5, 'ab')".to_owned()).into_sql_str()).execute(&pool).await.unwrap();
    let catalog = read_catalog_excluding_relations(&pool, &["app"], &[("app", "unused_data")])
        .await
        .unwrap();
    let table = &catalog.tables()[0];
    let columns = table
        .columns()
        .iter()
        .map(|column| (column.name(), column.column_type()))
        .collect::<std::collections::BTreeMap<_, _>>();
    let row = sqlx::query(
        AssertSqlSafe(
            "SELECT id, label, quantity::int4, ratio::float8, code::text FROM app.item".to_owned(),
        )
        .into_sql_str(),
    )
    .fetch_one(&pool)
    .await
    .unwrap();
    assert_eq!(row.get::<i64, _>(0), 7);
    assert!(row.get::<Option<String>, _>(1).is_none());
    assert_eq!(row.get::<i32, _>(2), 3);
    assert!(row.get::<f64, _>(3).is_finite());
    assert_eq!(columns["id"], SqlValueType::Int64);
    assert_eq!(columns["label"], SqlValueType::Text);
    assert_eq!(columns["quantity"], SqlValueType::Int32);
    assert_eq!(columns["ratio"], SqlValueType::Float64);
    assert_eq!(columns["code"], SqlValueType::Text);
    let view = &catalog.views()[0];
    assert_eq!(view.columns()[0].column_type(), SqlValueType::Int64);
    assert_eq!(view.columns()[1].column_type(), SqlValueType::Text);
    assert!(
        view.columns()
            .iter()
            .all(|column| column.origin().is_some())
    );
    pool.close().await;
}

#[tokio::test]
#[ignore = "requires: docker"]
async fn selected_column_and_constraint_refusals_remain() {
    let server = wamn_test_infrastructure::containers::start_postgres()
        .await
        .unwrap();
    for (case, (definition, expected)) in [
        (
            "CREATE TABLE app.dock (dock_id uuid NOT NULL, CONSTRAINT incorrect EXCLUDE USING gist (dock_id WITH =))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE app.dock (dock_id uuid NOT NULL, CONSTRAINT dock_dock_id_excl EXCLUDE USING btree (dock_id WITH =))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE app.dock (dock_id uuid NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL, CONSTRAINT dock_excl EXCLUDE USING gist (dock_id WITH =, tstzrange(starts_at, ends_at) WITH &&) WHERE (ends_at > starts_at))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE app.dock (dock_id uuid NOT NULL, CONSTRAINT dock_dock_id_excl EXCLUDE USING gist (dock_id WITH =) DEFERRABLE INITIALLY DEFERRED)",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
        (
            "CREATE TABLE app.item (id date)",
            PostgresIntrospectionErrorType::UnsupportedColumnType,
        ),
        (
            "CREATE TABLE app.item (name text DEFAULT lower('CLOSED'))",
            PostgresIntrospectionErrorType::UnsupportedColumnDefault,
        ),
        (
            "CREATE TABLE app.item (name text, computed text GENERATED ALWAYS AS (lower(name)) VIRTUAL)",
            PostgresIntrospectionErrorType::UnsupportedGeneratedColumn,
        ),
        (
            "CREATE TABLE app.item (name text); CREATE INDEX item_name_expression_idx ON app.item(lower(name))",
            PostgresIntrospectionErrorType::UnsupportedIndex,
        ),
        (
            "CREATE TABLE app.item (name text); CREATE INDEX refused_name ON app.item(name)",
            PostgresIntrospectionErrorType::UnsupportedIndex,
        ),
        (
            "CREATE TABLE app.item (name text); CREATE INDEX item_name_name_idx ON app.item(name,name)",
            PostgresIntrospectionErrorType::UnsupportedIndex,
        ),
        (
            "CREATE TABLE app.item (name text CONSTRAINT refused_name CHECK (name <> ''))",
            PostgresIntrospectionErrorType::UnsupportedConstraint,
        ),
    ]
    .into_iter()
    .enumerate()
    {
        let database = server
            .create_database(&format!("case_{case}"))
            .await
            .unwrap();
        let pool = wamn_postgres::pool(database.as_str(), 4).await.unwrap();
        sqlx::raw_sql(
            AssertSqlSafe(format!(
                "CREATE EXTENSION btree_gist; CREATE SCHEMA app; {definition}"
            ))
            .into_sql_str(),
        )
        .execute(&pool)
        .await
        .unwrap();
        assert_eq!(
            read_catalog(&pool, &["app"])
                .await
                .unwrap_err()
                .error_type(),
            expected
        );
        pool.close().await;
    }
}

#[tokio::test]
#[ignore = "requires: docker"]
async fn views_preserve_origins_expansion_dependencies_and_set_returning_functions() {
    let server = wamn_test_infrastructure::containers::start_postgres()
        .await
        .unwrap();
    let database = server.create_database("tests").await.unwrap();
    let pool = wamn_postgres::pool(database.as_str(), 4).await.unwrap();
    sqlx::raw_sql(
        AssertSqlSafe(
            "CREATE SCHEMA app;
        CREATE TABLE app.item (id bigint, label text);
        CREATE TABLE app.other (id bigint);
        CREATE VIEW app.inner_view (direct, computed, expanded_id, expanded_label) AS
            SELECT item.id, upper(label), (item).* FROM app.item JOIN app.other USING (id);
        CREATE VIEW app.outer_view AS SELECT * FROM app.inner_view;
        CREATE VIEW app.expanded AS SELECT id, unnest(ARRAY[id]) AS each FROM app.item"
                .to_owned(),
        )
        .into_sql_str(),
    )
    .execute(&pool)
    .await
    .unwrap();
    let catalog = read_catalog(&pool, &["app"]).await.unwrap();
    let view = |name| {
        catalog
            .views()
            .iter()
            .find(|view| view.name() == name)
            .unwrap()
    };
    let inner = view("inner_view");
    let item = catalog
        .tables()
        .iter()
        .find(|table| table.name() == "item")
        .unwrap();
    for (view_column, source_column) in [(0, 0), (2, 0), (3, 1)] {
        assert_eq!(
            inner.columns()[view_column].origin(),
            Some(&wamn_schema::ir::ViewColumnOrigin {
                schema: item.schema().into(),
                table: item.name().into(),
                column: item.columns()[source_column].name().into(),
            })
        );
    }
    assert!(inner.columns()[1].origin().is_none());
    assert_eq!(view("outer_view").base_tables(), inner.base_tables());
    assert_eq!(
        inner
            .base_tables()
            .iter()
            .map(wamn_schema::ir::ViewBaseTable::name)
            .collect::<std::collections::BTreeSet<_>>(),
        catalog
            .tables()
            .iter()
            .map(wamn_schema::ir::Table::name)
            .collect()
    );
    assert!(view("expanded").has_set_returning_functions());
    assert!(!inner.has_set_returning_functions());
    assert!(view("expanded").columns()[0].origin().is_some());
    assert!(view("expanded").columns()[1].origin().is_none());
    pool.close().await;
}

#[tokio::test]
#[ignore = "requires: docker"]
async fn selected_relations_retain_outgoing_and_incoming_foreign_keys() {
    use wamn_schema::ir::{ConstraintType, ForeignKeyAction};
    let server = wamn_test_infrastructure::containers::start_postgres()
        .await
        .unwrap();
    let database = server.create_database("tests").await.unwrap();
    let pool = wamn_postgres::pool(database.as_str(), 4).await.unwrap();
    sqlx::raw_sql(AssertSqlSafe("CREATE SCHEMA app;
        CREATE SCHEMA platform;
        CREATE TABLE platform.\"user\" (id uuid PRIMARY KEY);
        CREATE TABLE app.parent (id bigint PRIMARY KEY, unrelated date);
        CREATE TABLE app.selected (id bigint CONSTRAINT selected_id_pkey PRIMARY KEY,
            parent_id bigint REFERENCES app.parent(id),
            created_by uuid NOT NULL REFERENCES platform.\"user\" (id) ON DELETE RESTRICT);
        CREATE TABLE app.child (id bigint, selected_id bigint REFERENCES app.selected(id), unrelated date)".to_owned()).into_sql_str()).execute(&pool).await.unwrap();
    let catalog =
        read_catalog_excluding_relations(&pool, &["app"], &[("app", "parent"), ("app", "child")])
            .await
            .unwrap();
    assert!(
        catalog.tables()[0]
            .constraints()
            .iter()
            .any(|constraint| matches!(
                constraint.constraint_type(),
                ConstraintType::ForeignKey { referenced_table, .. }
                    if referenced_table.as_ref() == "parent"
            ))
    );
    assert!(catalog.tables()[0].constraints().iter().any(|constraint| {
        matches!(constraint.constraint_type(), ConstraintType::ForeignKey {
            columns, referenced_schema, referenced_table, on_delete: ForeignKeyAction::Restrict, ..
        } if referenced_schema.as_ref() == "platform" && referenced_table.as_ref() == "user"
            && matches!(columns.as_ref(), [column]
                if column.column() == "created_by" && column.referenced_column() == "id"))
    }));
    assert!(!catalog.referencing_constraints().is_empty());
    assert!(
        catalog
            .referencing_constraints()
            .iter()
            .all(|constraint| matches!(
                constraint.constraint_type(),
                ConstraintType::ForeignKey { referenced_table, .. } if referenced_table.as_ref() == catalog.tables()[0].name()
            ))
    );
    pool.close().await;
}
